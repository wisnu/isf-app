#!/usr/bin/env bash
# Generate DDL schema baru isf-app (otorisasi, dwh) dari DB referensi isf-app,
# dibersihkan agar kompatibel PostgreSQL 12 (server produksi legacy = PG 12.22).
#
# Pemakaian:
#   PGPASSWORD=solusi tools/gen_new_schema_ddl.sh [REF_DB] [OUT_DIR]
#   default REF_DB=mziss_laz  OUT_DIR=<dir skrip>/../zakat
#
# Pembersihan pg_dump 18 → PG12:
#   - hapus meta-command \restrict / \unrestrict (psql 18+)
#   - hapus SET transaction_timeout (PG17+)
#   - "CONSTRAINT <x>_not_null NOT NULL" → "NOT NULL" (named NOT NULL = PG18)
set -euo pipefail
REF_DB="${1:-mziss_laz}"
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT_DIR="${2:-$HERE/../zakat}"
PGHOST="${PGHOST:-localhost}"; PGPORT="${PGPORT:-5432}"; PGUSER="${PGUSER:-transaction}"
export PGHOST PGPORT PGUSER

clean() {
  sed -E \
    -e '/^\\(un)?restrict /d' \
    -e '/^SET transaction_timeout/d' \
    -e 's/CONSTRAINT [a-z0-9_]+_not_null NOT NULL/NOT NULL/g' \
    -e '/^-- Dumped (from|by)/d'
}

dump() { # $1=schema $2=outfile $3=title
  {
    echo "-- $3"
    echo "-- GENERATED by tools/gen_new_schema_ddl.sh dari DB referensi '$REF_DB' — jangan edit manual."
    echo "-- Kompatibel PostgreSQL 12+. Dijalankan oleh run_migration.sh dalam satu transaksi."
    pg_dump -d "$REF_DB" -s -n "$1" --no-owner --no-acl --no-comments | clean
  } > "$2"
  echo "wrote $2 ($(grep -c '^CREATE' "$2") CREATE statements)"
}

dump otorisasi "$OUT_DIR/02_schema_otorisasi.sql" "Schema otorisasi (maker-checker) — tabel, sequence, index, constraint"
dump dwh       "$OUT_DIR/03_schema_dwh.sql"       "Schema dwh (datamart + view laporan) — tabel, sequence, view, index, constraint"
