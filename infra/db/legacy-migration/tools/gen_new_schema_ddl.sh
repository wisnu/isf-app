#!/usr/bin/env bash
# Generate DDL schema baru isf-app (otorisasi, dwh) dari DB referensi isf-app,
# dibersihkan agar kompatibel PostgreSQL 12 (server produksi legacy = PG 12.22).
#
# Pemakaian:
#   PGPASSWORD=solusi tools/gen_new_schema_ddl.sh [REF_DB] [OUT_DIR] [REF_AUTH_DB]
#   default REF_DB=mziss_laz  OUT_DIR=<dir skrip>/../zakat  REF_AUTH_DB=isf_auth_zakat
#
# Output:
#   OUT_DIR/02_schema_otorisasi.sql, 03_schema_dwh.sql   (business DB)
#   OUT_DIR/auth/11_schema_isf_auth.sql                    (auth DB, schema)
#   OUT_DIR/auth/12_reference_data.sql                     (auth DB: tenants, menu, role_menu_permission)
#
# Pembersihan pg_dump 18 → PG12:
#   - hapus meta-command \restrict / \unrestrict (psql 18+)
#   - hapus SET transaction_timeout (PG17+)
#   - "CONSTRAINT <x>_not_null NOT NULL" → "NOT NULL" (named NOT NULL = PG18)
set -euo pipefail
REF_DB="${1:-mziss_laz}"
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT_DIR="${2:-$HERE/../zakat}"
REF_AUTH_DB="${3:-isf_auth_zakat}"
PGHOST="${PGHOST:-localhost}"; PGPORT="${PGPORT:-5432}"; PGUSER="${PGUSER:-transaction}"
export PGHOST PGPORT PGUSER

clean() {
  sed -E \
    -e '/^\\(un)?restrict /d' \
    -e '/^SET transaction_timeout/d' \
    -e 's/CONSTRAINT [a-z0-9_]+_not_null NOT NULL/NOT NULL/g' \
    -e '/^-- Dumped (from|by)/d'
}

dump() { # $1=schema $2=outfile $3=title [$4=db]
  local db="${4:-$REF_DB}"
  {
    echo "-- $3"
    echo "-- GENERATED by tools/gen_new_schema_ddl.sh dari DB referensi '$db' — jangan edit manual."
    echo "-- Kompatibel PostgreSQL 12+. Dijalankan oleh runner dalam satu transaksi."
    pg_dump -d "$db" -s -n "$1" --no-owner --no-acl --no-comments | clean
  } > "$2"
  echo "wrote $2 ($(grep -c '^CREATE' "$2") CREATE statements)"
}

dump otorisasi "$OUT_DIR/02_schema_otorisasi.sql" "Schema otorisasi (maker-checker) — tabel, sequence, index, constraint"
dump dwh       "$OUT_DIR/03_schema_dwh.sql"       "Schema dwh (datamart + view laporan) — tabel, sequence, view, index, constraint"

# ── Auth DB (isf_auth_<portal>) ──────────────────────────────────────────────
mkdir -p "$OUT_DIR/auth"
dump isf_auth "$OUT_DIR/auth/11_schema_isf_auth.sql" "Schema isf_auth (identitas, kredensial, tenant, menu, RBAC)" "$REF_AUTH_DB"

# Data referensi = config, BUKAN data user (users/credentials/memberships diprovisikan
# dari enterprise.userapp produksi oleh tools/provision_auth_users.py; audit_log tidak dibawa).
{
  echo "-- Data referensi isf_auth: tenants, menu, role_menu_permission"
  echo "-- GENERATED by tools/gen_new_schema_ddl.sh dari '$REF_AUTH_DB' ($(date +%F)) — jangan edit manual."
  echo "-- Idempotent (ON CONFLICT DO NOTHING). Kompatibel PostgreSQL 12+."
  pg_dump -d "$REF_AUTH_DB" --data-only --column-inserts --on-conflict-do-nothing \
    --no-owner --no-acl -t isf_auth.tenants -t isf_auth.menu -t isf_auth.role_menu_permission | clean
} > "$OUT_DIR/auth/12_reference_data.sql"
echo "wrote $OUT_DIR/auth/12_reference_data.sql ($(grep -c '^INSERT' "$OUT_DIR/auth/12_reference_data.sql") INSERT)"
